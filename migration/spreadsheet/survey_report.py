"""The phase-0 survey as a Markdown table: one row per workbook (runs/survey/*.json)."""
import json, os, sys
d = sys.argv[1]
rows = []
for f in sorted(os.listdir(d)):
    if not f.endswith('.json'): continue
    try: s = json.load(open(os.path.join(d, f)))
    except Exception:
        err = open(os.path.join(d, f[:-5] + '.err')).read().strip().splitlines()
        rows.append(f"| {f[:-5]} | — | — | — | — | not read: {(err[-1] if err else 'timeout')[:100]} |"); continue
    n = s['formulas']; same = s['recomputed_same']
    pct = f"{100*same/n:.1f}%" if n else "—"
    fns = ', '.join(f"{k} {v}" for k, v in list(s['functions'].items())[:8])
    dfs = ', '.join(f"{k} {v}" for k, v in list(s.get('differ_functions', {}).items())[:5]) or '—'
    hidden = sum(1 for x in s['sheets'] if x['state'] != 'visible')
    rows.append(f"| {s['file']} | {len(s['sheets'])} ({hidden} hidden){' + macros' if s['macros'] else ''} | {n} | {pct} ({s['recomputed_differ']} differ, {s['cachedErrors']} saved as errors) | {fns} | {dfs} |")
print("# Phase 0 survey: how much of each workbook the sheet engine recomputes as Excel saved it\n")
print("*Generated by survey_report.py from runs/survey (survey.sh) or runs/survey_corpus (survey_corpus.sh). Each formula cell is recomputed by LE2's sheet engine (Formualizer, WebAssembly) from the workbook as saved, and compared with the value Excel saved for it. A cell Excel saved as an error counts as the same when the engine gives the same error.*\n")
print("| Workbook | Sheets | Formulas | Recomputed as saved | Most used functions | Functions in the cells that differ |")
print("|---|---|---|---|---|---|")
print('\n'.join(rows))
